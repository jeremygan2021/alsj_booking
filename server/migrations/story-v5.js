const knownVersions = [version2, version3, version4];

async function upgradeFields(db, table, row, fields, previousRows) {
  for (const [field, index] of fields) {
    const previous = [
      ...new Set(previousRows.map((old) => old?.[index])),
    ].filter((value) => value !== undefined && value !== row[index]);
    for (const value of previous) {
      await db
        .prepare(`UPDATE ${table} SET ${field}=? WHERE id=? AND ${field}=?`)
        .run(row[index], row[0], value);
    }
  }
}

// Run inside the caller's database transaction, after applyNpcMaterials.
// No DROP/DELETE, no gameplay-state reset, and no overwrite based merely on a migration marker.
export async function applyStoryV5(db) {
  const id = "story-v5";
  if (await db.prepare("SELECT id FROM content_migrations WHERE id=?").get(id))
    return;
  for (const row of npcs) {
    await db
      .prepare(
        "INSERT OR IGNORE INTO npcs(id,name,english,role,bio,secret) VALUES(?,?,?,?,?,?)",
      )
      .run(...row);
    await upgradeFields(
      db,
      "npcs",
      row,
      [
        ["name", 1],
        ["english", 2],
        ["role", 3],
        ["bio", 4],
        ["secret", 5],
      ],
      knownVersions.map((v) => v.npcs.find((old) => old[0] === row[0])),
    );
  }
  for (const row of evidence) {
    await db
      .prepare(
        "INSERT OR IGNORE INTO clues(id,title,area,skill,dc,body,detail,category,phase) VALUES(?,?,?,?,?,?,?,?,?)",
      )
      .run(...row, evidencePhases.get(row[0]) ?? 3);
    await upgradeFields(
      db,
      "clues",
      row,
      [
        ["title", 1],
        ["area", 2],
        ["skill", 3],
        ["dc", 4],
        ["body", 5],
        ["detail", 6],
        ["category", 7],
      ],
      knownVersions.map((v) => v.evidence.find((old) => old[0] === row[0])),
    );
  }
  for (const [index, lot] of lots.entries()) {
    const row = [index + 1, ...lot];
    await db
      .prepare(
        "INSERT OR IGNORE INTO lots(id,title,start_price,description,effect) VALUES(?,?,?,?,?)",
      )
      .run(...row);
    await upgradeFields(
      db,
      "lots",
      row,
      [
        ["title", 1],
        ["start_price", 2],
        ["description", 3],
        ["effect", 4],
      ],
      knownVersions.map((v) =>
        v.lots[index] ? [index + 1, ...v.lots[index]] : undefined,
      ),
    );
  }
  await db.prepare("INSERT INTO content_migrations(id) VALUES(?)").run(id);
}
