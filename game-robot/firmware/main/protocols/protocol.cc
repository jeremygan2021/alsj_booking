void Protocol::AddTextFontCapabilities(cJSON* root) {
    auto capability = Assets::GetInstance().text_font_capability();
    cJSON* features = cJSON_GetObjectItem(root, "features");
    if (cJSON_IsObject(features)) {
        cJSON_AddBoolToObject(features, "glyph_push", capability.glyph_push);
#ifdef CONFIG_BOARD_TYPE_ECHO_GAME_DISP_V1
        cJSON_AddStringToObject(features, "game_role", "echo-archivist");
        cJSON_AddBoolToObject(features, "mission_control", false);
        cJSON_AddBoolToObject(features, "wheel_drive", false);
        cJSON_AddBoolToObject(features, "agent_control", false);
        cJSON_AddBoolToObject(features, "playback_tasks", false);
        cJSON_AddBoolToObject(features, "capture_tasks", false);
        cJSON_AddBoolToObject(features, "control_only", false);
        cJSON_DeleteItemFromObject(features, "mcp");
        cJSON_AddBoolToObject(features, "mcp", false);
#endif
    }

    if (!capability.glyph_push) {
        return;
    }
    cJSON* font = cJSON_CreateObject();
    cJSON_AddStringToObject(font, "bundle", capability.bundle.c_str());
    cJSON_AddStringToObject(font, "charset", capability.charset.c_str());
    cJSON_AddNumberToObject(font, "size", capability.size);
    cJSON_AddNumberToObject(font, "bpp", capability.bpp);
    cJSON_AddItemToObject(root, "text_font", font);
}

