"""Write projection and silent-NPC cue cards from actual mixed-audio timings."""
from pathlib import Path
import json

ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'交付包_阿拉斯加之夜'/'现场演绎音频'
tracks={t['id']:t for t in json.loads((OUT/'播放清单.json').read_text())['tracks']}
def ts(s):return f'{int(s)//60:02d}:{int(s)%60:02d}'

b=tracks['B02']
labels=['极光庄园','万圣节来客','瑟琳娜记忆展厅','ECHO数字演示','六位人物关系','命运拍卖厅']
text='# B02 万圣节图文投屏卡\n\n播放 `B02_阿拉斯加万圣节之夜_投屏版.mp4`，时长2:57，已包含MiniMax旁白和背景音乐。不要再同时播放B02 MP3。全屏投影，音频从投影电脑送到现场调音台。\n\n| 画面开始 | 画面 | 旁白主题 |\n|---|---|---|\n'
times=[0]+[line['start'] for line in b['lines'][1:]]
for i,(when,label) in enumerate(zip(times,labels)):
 text+=f'| {ts(when)} | {i+1:02d} {label} | {b["lines"][i]["text"].split("。")[0]} |\n'
text+='\n画面刻意保持公开信息口径，暗线、凶手和预录时间诡计留给后续调查。画面为AI生成场景示意，不是角色真人肖像。\n'
(OUT/'万圣节图文'/'投屏与画面顺序.md').write_text(text)

b=tracks['B03']
actions={
 '主持人':'独立男主持在台侧报幕或收尾，不占用六名NPC的入场位置。',
 '西奥多':'女拍卖师持拍卖槌独立入场，向来宾点头，站到拍卖台旁。',
 '索恩':'从主入口上场，站到中央，向来宾举杯。',
 '伊芙琳':'从展厅方向入场，在ECHO演示台旁停步。',
 '里昂':'从侧门入场，整理账册或袖口，站在索恩侧后。',
 '克拉拉':'从照片展区入场，轻触展签或看向瑟琳娜的照片。',
 '诺拉':'男性FBI探员从通道入场，展示证件，站在出入口旁。',
}
text=f'# B03 六位人物出场走位卡（GM/演员）\n\n播放总长{ts(b["duration"])}。独立男主持报幕、收尾；六名NPC分别自报全名。西奥多使用女声，诺拉使用男声并公开FBI身份。演员听到自己的声音即入场、定点、做一个动作，不必开口。\n\n| 声音起点 | 角色 | 真人动作 |\n|---|---|---|\n'
for line in b['lines']:text+=f'| {ts(line["start"])} | {line["role"]} | {actions[line["role"]]} |\n'
text+='\n演员随音频做短动作即可，不必逐字对口型。下一位声音响起时，上一位保持定点，避免走位遮挡。\n'
(OUT/'人物出场走位卡_GM.md').write_text(text)

